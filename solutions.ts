function multiplyValue(value: number, multiplier?: number): number {
    if (multiplier !== undefined) {
        return value * multiplier;
    } else {
        return value * 2;
    }
}

console.log(multiplyValue(10));    
console.log(multiplyValue(10, 5)); 
console.log(multiplyValue(7, 0)); 



